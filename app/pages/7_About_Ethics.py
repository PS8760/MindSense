st.subheader("Known limitations")
st.markdown(
    """
1. **Self-selection bias** — the DASS-42 and OSMI samples are people who chose
   to take an online test; group rates are not population prevalence.
2. **Label noise** — sentiment labels are corpus annotations, not clinician
   diagnoses; the 7-class corpus overlaps 2 819 posts with Dreaddit
   (quantified in `reports/tables/text_leakage_report.json`).
3. **Demographic coverage** — gender beyond male/female/other and non-English
   texts are under-represented; fairness tables (Exp 8) show where errors are
   uneven.
4. **Associations only** — the what-if sliders move a model's input, not a
   causal world; no interventional claims are made anywhere in the app.
5. **No personal longitudinal data** — the mood tracker is session-only by
   design; we do not collect or store histories.
6. **Regulatory** — this is not a medical device and makes no CE/FDA-style
   claims; it must not be deployed for clinical or insurance decisions.
"""
)

