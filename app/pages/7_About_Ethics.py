st.subheader("Privacy & data handling")
st.markdown(
    """
- **In-memory only.** Questionnaire answers, text and photos stay in this
  session's memory (Streamlit `session_state`). Nothing is uploaded to a server
  or written to disk by the app.
- **No accounts, no tracking, no cookies** beyond the session itself. Close the
  tab and the data is gone.
- **Photos are never saved.** The face module processes bytes in memory; the
  image is discarded after inference.
- **No row-level data in git.** `data/raw/` and `data/processed/` are
  git-ignored; only aggregate reports are committed (DECISIONS #13).
- **Helplines** in `config/helplines.yaml` are public service numbers, verified
  on 2026-10-08.
"""
)

